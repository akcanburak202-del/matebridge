func seal(key: String, counter: UInt64, type: UInt8, payload: Data) -> [String: String] {
    let plaintext = Data([type]) + payload
    let length = le32(UInt32(plaintext.count + 16))
    let nonce = Data(repeating: 0, count: 4) + le64(counter)
    let box = try! AES.GCM.seal(plaintext, using: SymmetricKey(data: bytes(key)),
                                nonce: AES.GCM.Nonce(data: nonce), authenticating: length)
    return ["key": key, "counter": String(counter), "type": String(format: "0x%02x", type), "payload": hex(payload),
            "nonce": hex(nonce), "frame": hex(length + box.ciphertext + box.tag)]
}

