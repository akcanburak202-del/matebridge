func expand(_ prk: Data, _ info: String, _ extra: Data = Data(), _ n: Int) -> Data {
    // HKDF-Expand (RFC 5869) with SHA-256.
    var out = Data(); var t = Data(); var i: UInt8 = 1
    while out.count < n {
        var h = HMAC<SHA256>(key: SymmetricKey(data: prk))
        h.update(data: t); h.update(data: Data(info.utf8) + extra); h.update(data: [i])
        t = Data(h.finalize()); out += t; i += 1
    }
    return out.prefix(n)
}
func extract(salt: Data, ikm: Data) -> Data {
    Data(HMAC<SHA256>.authenticationCode(for: ikm, using: SymmetricKey(data: salt)))
}

